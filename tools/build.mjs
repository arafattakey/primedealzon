// Builds the static, indexable parts of the site from js/data.js:
//   guides/<slug>/index.html  (one page per guide, full content in the HTML)
//   sitemap.xml, robots.txt
// Run from anywhere:  node tools/build.mjs     (no dependencies)
// Run it after every change to POSTS, PRODUCTS, CATEGORIES or SITE.url, then commit the output.
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ctx = vm.createContext({ URLSearchParams });
for (const f of ['js/data.js', 'js/site.js']) vm.runInContext(readFileSync(join(root, f), 'utf8'), ctx, { filename: f });
const { SITE, POSTS, CATEGORIES, guideHtml, esc, catById } = vm.runInContext('({ SITE, POSTS, CATEGORIES, guideHtml, esc, catById })', ctx);

const base = SITE.url.endsWith('/') ? SITE.url : SITE.url + '/';
const isoDate = (s) => new Date(s).toLocaleDateString('en-CA'); // YYYY-MM-DD
const json = (o) => JSON.stringify(o, null, 2).replace(/</g, '\\u003c');

function page(post) {
  const url = `${base}guides/${post.slug}/`;
  const c = catById(post.cat);
  const published = isoDate(post.date);
  const modified = isoDate(post.updated || post.date);
  const title = `${post.title} – ${SITE.name}`;
  const ld = [
    {
      '@context': 'https://schema.org',
      '@type': 'Article',
      headline: post.title,
      description: post.excerpt,
      datePublished: published,
      dateModified: modified,
      mainEntityOfPage: url,
      author: { '@type': 'Organization', name: `${SITE.name} team`, url: base + 'about.html' },
      publisher: { '@type': 'Organization', name: SITE.name, url: base },
    },
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: base },
        { '@type': 'ListItem', position: 2, name: 'Guides', item: base + 'blog.html' },
        { '@type': 'ListItem', position: 3, name: post.title, item: url },
      ],
    },
  ];
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(post.excerpt)}" />
  <link rel="canonical" href="${url}" />
  <meta name="theme-color" content="#15161a" />
  <meta property="og:type" content="article" />
  <meta property="og:site_name" content="${esc(SITE.name)}" />
  <meta property="og:title" content="${esc(post.title)}" />
  <meta property="og:description" content="${esc(post.excerpt)}" />
  <meta property="og:url" content="${url}" />
  <meta property="article:published_time" content="${published}" />
  <meta property="article:modified_time" content="${modified}" />
  <meta property="article:section" content="${esc(c.name)}" />
  <meta name="twitter:card" content="summary" />
  <link rel="icon" href="../../favicon.svg" type="image/svg+xml" />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,600;1,9..144,600&family=Inter:wght@400;500;600;700;800&display=swap" />
  <link rel="stylesheet" href="../../css/style.css" />
  <script type="application/ld+json">
${json(ld)}
  </script>
</head>
<body data-page="guide" data-root="../../">
  <!-- Generated by tools/build.mjs from js/data.js. Edit the data, not this file. -->
  <div class="disclosure-bar">We earn a commission from qualifying Amazon purchases made through our links, at no extra cost to you. <a href="../../disclaimer.html">Learn more</a></div>
  <header class="site-header" id="site-header"></header>

  <main id="postRoot">${guideHtml(post)}
  </main>

  <footer class="site-footer" id="site-footer"></footer>
  <script src="../../js/data.js"></script>
  <script src="../../js/site.js"></script>
</body>
</html>
`;
}

// 1. Guide pages (remove folders for guides that no longer exist)
const guidesDir = join(root, 'guides');
const slugs = new Set(POSTS.map((p) => p.slug));
if (existsSync(guidesDir)) {
  for (const d of readdirSync(guidesDir, { withFileTypes: true })) {
    if (d.isDirectory() && !slugs.has(d.name)) rmSync(join(guidesDir, d.name), { recursive: true });
  }
}
for (const post of POSTS) {
  if (!/^[a-z0-9-]+$/.test(post.slug)) throw new Error(`Bad slug: ${post.slug}`);
  const dir = join(guidesDir, post.slug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.html'), page(post));
}

// 2. Sitemap
const siteDate = isoDate(SITE.updated);
const urls = [
  ['', siteDate], ['category.html', siteDate], ['blog.html', siteDate], ['about.html', siteDate],
  ['disclaimer.html', siteDate], ['privacy.html', siteDate],
  ...CATEGORIES.map((c) => [`category.html?cat=${c.id}`, siteDate]),
  ...POSTS.map((p) => [`guides/${p.slug}/`, isoDate(p.updated || p.date)]),
];
writeFileSync(join(root, 'sitemap.xml'),
  '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  urls.map(([u, d]) => `  <url><loc>${esc(base + u)}</loc><lastmod>${d}</lastmod></url>`).join('\n') +
  '\n</urlset>\n');

// 3. robots.txt
writeFileSync(join(root, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${base}sitemap.xml\n`);

console.log(`Built ${POSTS.length} guide pages, sitemap with ${urls.length} URLs.`);
